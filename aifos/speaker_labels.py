"""说话人标签的唯一事实源:哪些"说话人"根本不是人物。

刻意做成零依赖叶子模块。旁白/音效被当成人物这个问题修好又复发过几次,
原因之一就是判定函数寄生在 script_import 里,而 script_import 反向依赖
编剧适配桥——任何新的校验环节想复用它都会撞上循环导入,于是要么绕过、
要么各写各的。放在这里之后,任何一层都能直接 import,没有任何借口。

新增校验环节时的规矩:凡是要判断"某个名字是不是人物",一律调用
``is_non_person_label``,不要另起炉灶。
"""

# 旁白、音效、字幕这类"叙事装置"在剧本里长得和人物完全一样
# (「旁白:夜色渐深」「音效:雷声」)。一旦被当成人物就会生成立绘、
# 占用候选额度、污染每镜人数,还会被质检当成"多余人物"反复打回。
_NON_PERSON_EXACT = frozenset({
    "os", "o.s.", "vo", "v.o.", "se", "sfx", "bgm",
    "音乐", "静音", "静默", "无声", "画外", "系统", "系统提示",
    "叙述者", "讲述人", "旁白者", "解说员", "字幕组",
})
_NON_PERSON_TOKENS = (
    "旁白", "画外音", "画外白", "独白", "心声", "心理活动",
    "解说", "叙述", "音效", "声效", "配乐", "背景音乐", "环境音",
    "字幕", "花字", "提示音", "广播", "播报", "音轨", "片头", "片尾",
    "bgm", "sfx",
)

_STRIP_CHARS = " \t，。！？；、:：()（）【】[]〔〕<>《》"


def is_non_person_label(value):
    """旁白/音效/字幕等叙事装置不是人物,永远不得生成人物资产。

    与 ``is_likely_performance_label`` 的区别很重要,决定了处置方式:
    表演提示词(“沉声”)是**归并**问题——它属于某个真实人物,要靠 AI 归
    并回去,归并不了就请人工确认;旁白音效是**排除**问题——它不属于任何
    人物,直接静默剔除即可,不需要也不应该打断用户。
    """
    value = str(value or "").strip(_STRIP_CHARS)
    if not value:
        return False
    folded = value.lower()
    if folded in _NON_PERSON_EXACT:
        return True
    return any(token in folded for token in _NON_PERSON_TOKENS)
